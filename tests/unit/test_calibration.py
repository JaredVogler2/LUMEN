@pytest.mark.parametrize("which", ["checkerboard", "charuco"])
def test_detection_accuracy_against_truth(which, chk_shots, chu_shots):
    photos, obs = chk_shots if which == "checkerboard" else chu_shots
    spec = SPEC_CHK if which == "checkerboard" else SPEC_CHU
    assert all(o.ok and o.quality.complete and o.n_points == spec.n_corners for o in obs)
    err = np.concatenate([o.image_points - p.corners_px[o.ids] for o, p in zip(obs, photos)])
    per_view = [rms2d(o.image_points - p.corners_px[o.ids]) for o, p in zip(obs, photos)]
    worst = float(np.linalg.norm(err, axis=1).max())
    note(f"detection {which}: RMS / |mean u| / |mean v| / max / worst view RMS [px], {len(err)} corners", (round(rms2d(err), 4), round(abs(err[:, 0].mean()), 4), round(abs(err[:, 1].mean()), 4), round(worst, 4), round(max(per_view), 4)))
    assert rms2d(err) < 0.055 and worst < 0.25 and max(per_view) < 0.08
    assert np.all(np.abs(err.mean(axis=0)) < 0.01)  # no systematic offset: the pixel-centre convention holds
    for o, p in zip(obs, photos):
        q = o.quality
        assert np.array_equal(o.ids, np.arange(spec.n_corners)) and o.object_points.shape == (spec.n_corners, 3) and np.all(o.object_points[:, 2] == 0)
        assert abs(q.tilt_deg - p.tilt_deg) < 3.0, "tilt estimated from one photo, before any calibration"
        assert 0.8 < q.blur_px < 1.3 and not q.blur_saturated and q.contrast > 0.8 and not q.partly_outside and q.missing_inside == 0
        assert 0.04 < q.coverage < 0.4 and q.min_square_px > 30 and o.warnings == []
        json.dumps(o.to_dict())
    note(f"detection {which}: tilt estimate before calibration, max error [deg]", round(max(abs(o.quality.tilt_deg - p.tilt_deg) for o, p in zip(obs, photos)), 2))


