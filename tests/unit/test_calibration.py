def test_corner_numbering_is_made_canonical_whatever_order_the_detector_returns(chk_shots):
    """The detector may number an asymmetric board from either end, or mirrored;
    the square colours and the handedness fix it."""
    from lumen.vision.calibration import _canonical_chessboard

    photo = chk_shots[0][4]
    gray = cv2.cvtColor(photo.image, cv2.COLOR_BGR2GRAY)
    truth = photo.corners_px.reshape(6, 9, 2)
    for label, grid, mirrored, turned in (("as is", truth, False, False), ("half turn", truth[::-1, ::-1], False, True), ("each row backwards", truth[:, ::-1], True, False), ("rows in reverse order", truth[::-1], True, True)):
        out, info = _canonical_chessboard(gray, np.ascontiguousarray(grid).reshape(-1, 2), 9, 6)
        assert np.allclose(out, photo.corners_px), label
        assert (info["mirrored_numbering"], info["half_turn_applied"], info["origin_square"]) == (mirrored, turned, "black"), label


