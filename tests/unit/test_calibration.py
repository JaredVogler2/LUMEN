    assert by_id["misdetected"]["rms_px"] > 5 * by_id["misdetected"]["median_rms_px"]
    assert [v["used"] for v in res.views].count(False) == 2 and res.views[7]["excluded"] == ["reprojection_outlier"] and res.views[5]["excluded"] == ["too_blurred"]
    assert np.all(np.abs(params_of(res.camera) - TRUTH)[:8] < 3.0 * np.array(res.param_sigma)[:8])
