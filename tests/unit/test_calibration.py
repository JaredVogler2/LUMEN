def test_planar_measurement_needs_the_distortion_function_not_the_focal_length(chk_cal, held_out):
    """Undistorted pixels are mapped to the plane by a homography, which absorbs the
    pose and any scale of the focal length: a model with 0.8 x the focal length
    and the correspondingly rescaled coefficients (the same distortion in the
    picture) measures the board identically.  What must be right is the
    distortion as a function of the pixel."""
    c, s = chk_cal.camera, 0.8
    k1, k2, p1, p2, k3 = c.dist
    same = CameraModel(c.width, c.height, s * c.fx, s * c.fy, c.cx, c.cy, (k1 * s**2, k2 * s**4, p1 * s, p2 * s, k3 * s**6))
    a, b = validate_planar(c, held_out[1]), validate_planar(same, held_out[1])
    for key in ("rms_px", "max_px", "rms_mm", "max_mm", "max_distance_error_mm"):
        assert b.with_model[key] == pytest.approx(a.with_model[key], rel=1e-6, abs=1e-9)
    # the focal length alone, without rescaling the coefficients, changes the distortion and shows
    wrong = validate_planar(CameraModel(c.width, c.height, s * c.fx, s * c.fy, c.cx, c.cy, c.dist), held_out[1])
    assert wrong.with_model["rms_px"] > 3.0 * a.with_model["rms_px"]


def test_fit_homography_is_exact_and_better_than_dlt_under_noise():
    rng = np.random.default_rng(0)
    Ht = np.array([[4.1, 0.3, 500.0], [-0.2, 3.7, 300.0], [4e-4, -6e-4, 1.0]])
    src = SPEC_CHK.corner_xy()
    dst = (np.c_[src, np.ones(len(src))] @ Ht.T)
    dst = dst[:, :2] / dst[:, 2:]
    assert np.allclose(fit_homography(src, dst), Ht, rtol=1e-9, atol=1e-9)
    noisy = dst + rng.normal(0, 0.5, dst.shape)
    from lumen.geometry.homography import apply_h, dlt_homography

    cost = lambda Hm: float(np.sum((apply_h(Hm, src) - noisy) ** 2))  # noqa: E731
    assert cost(fit_homography(src, noisy)) <= cost(dlt_homography(src, noisy)) + 1e-9


