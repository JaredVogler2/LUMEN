def _z_scores(base, n_sets: int, n_views: int, sigma_px: float, seed0: int):
    """Point-level Monte Carlo: (estimate - truth) / sigma over capture sets that
    differ in poses and noise, for the reported and for OpenCV's formal sigma."""
    truth = np.array([base.fx, base.fy, base.cx, base.cy, *base.dist])
    z_rep, z_formal, terms = [], [], set()
    for seed in range(n_sets):
        res = calibrate_camera(_simulate(CHK, SPEC_CHK, view_set(CHK, base, n_views, seed=seed0 + seed), sigma=sigma_px, seed=seed))
        assert res.ok
        terms.add(tuple(res.distortion["estimated"]))
        err = params_of(res.camera) - truth
        z_rep.append(err / np.array(res.param_sigma))
        with np.errstate(divide="ignore", invalid="ignore"):
            z_formal.append(err / np.array(res.param_sigma_formal))
    return np.sqrt(np.mean(np.square(z_rep), axis=0)), np.sqrt(np.mean(np.square(z_formal), axis=0)), terms


def test_reported_sigmas_are_honest_for_gaussian_corner_noise():
    """Point-level Monte Carlo (no detector), 24 capture sets of 9 photos.  The RMS of
    z = (estimate - truth) / sigma should be 1.

    * OpenCV's formal sigmas pass on their own (0.8 to 1.15 here) when the lens is
      inside the estimated model.
    * The reported sigmas are never smaller than those, so z <= 1.2; for k1, k2 they
      are deliberately larger (z of 0.15 to 0.3: three to seven times the scatter),
      because k3 is fixed at zero on the strength of photos that could not have
      excluded it (next test).
    """
    rep, formal, terms = _z_scores(BASE, 24, 9, 0.04, 300)
    note("sigma honesty, points + Gaussian noise, 24 sets x 9 views: RMS z with the reported sigma", dict(zip(PARAM_NAMES, np.round(rep, 2))))
    note("sigma honesty, points + Gaussian noise, 24 sets x 9 views: RMS z with OpenCV's formal sigma", dict(zip(PARAM_NAMES[:8], np.round(formal[:8], 2))))
    assert terms == {("k1", "k2", "p1", "p2")}
    assert np.all(formal[:8] > 0.65) and np.all(formal[:8] < 1.45), formal
    assert np.all(rep[:8] < 1.25), rep
    assert np.all(rep[[0, 1, 2, 3, 6, 7]] > 0.6) and np.all(rep[[4, 5]] > 0.08), rep


def test_reported_sigmas_cover_distortion_the_photos_cannot_determine():
    """Point-level Monte Carlo, 12 sets.  The lens has k3 = 0.05; with points reaching
    0.7 of the way to the picture corners the held-out photos do not ask for a k3,
    it stays at zero and k1, k2 absorb it.  Their formal sigmas are then many times
    too small; the reported ones, which contain the spread between the two models,
    are not."""
    lens = phone_base(W, H, dist=(0.08, -0.15, 0.0006, -0.0004, 0.05), pp_offset=(7.3, -5.1), aspect=1.001)
    rep, formal, terms = _z_scores(lens, 12, 9, 0.04, 300)
    note("lens with k3 = 0.05 that is not estimated, 12 sets: RMS z of k1, k2 with the reported / the formal sigma", (np.round(rep[4:6], 2).tolist(), np.round(formal[4:6], 2).tolist()))
    assert ("k1", "k2", "p1", "p2") in terms
    assert np.all(formal[4:6] > 3.0), "the least-squares sigmas alone would be badly optimistic here"
    assert np.all(rep[:9] < 1.8), rep


