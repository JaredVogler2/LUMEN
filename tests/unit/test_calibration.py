    note("photo with 18 px motion blur: measured edge spread [px] / corner RMS error [px]", (round(blurred.quality.blur_px, 2), round(rms2d(blurred.image_points - shaken.corners_px[blurred.ids]), 3)))
    # (b) a detection whose right half is displaced by 1.4 px (simulated mis-detection)
