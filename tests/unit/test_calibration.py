def note(key: str, value: object) -> None:
    MEASURED[key] = json.loads(json.dumps(value, default=float))


def rms2d(e: np.ndarray) -> float:
    return float(np.sqrt(np.mean(np.sum(e * e, axis=1))))


def params_of(cam: CameraModel) -> np.ndarray:
    return np.array([cam.fx, cam.fy, cam.cx, cam.cy, *cam.dist])


def _simulate(printed: PrintedBoard, spec: BoardSpec, cams, sigma: float = 0.03, seed: int = 0, size=None):
    """Observations from the true projection plus Gaussian noise (no detector involved)."""
    rng = np.random.default_rng(seed)
    out = []
    for k, cam in enumerate(cams):
        uv, seen = project_board_points(cam, printed.corners_mm())
        pts = uv[seen] + rng.normal(0.0, sigma, (int(seen.sum()), 2))
        out.append(observation_from_points(spec, size or (cam.width, cam.height), printed.corner_ids()[seen], pts, view_id=f"v{k}"))
    return out


